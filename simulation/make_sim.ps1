# Writes wokwi\sketch.ino from the real firmware, changing only the settings block:
# Wokwi's virtual Wi-Fi, the public HiveMQ broker without TLS, and shorter safety timers.
$ErrorActionPreference = 'Stop'
$src = Join-Path $PSScriptRoot '..\firmware\water_tank_controller\water_tank_controller.ino'
$dst = Join-Path $PSScriptRoot 'wokwi\sketch.ino'
$sim = 'nk7q2'                                    # keeps the topics unique on the public broker

$code = [IO.File]::ReadAllText($src)
$edits = [ordered]@{
  'const char\* WIFI_SSID = "[^"]*";'           = 'const char* WIFI_SSID = "Wokwi-GUEST";'
  'const char\* WIFI_PASS = "[^"]*";'           = 'const char* WIFI_PASS = "";'
  '#define USE_TLS 1'                           = '#define USE_TLS 0'
  'const char\* MQTT_HOST = "[^"]*";'           = 'const char* MQTT_HOST = "broker.hivemq.com";'
  'const int   MQTT_PORT = \d+;'                = 'const int   MQTT_PORT = 1883;'
  'const char\* MQTT_USER = "[^"]*";'           = 'const char* MQTT_USER = nullptr;'
  'const char\* MQTT_PASS = "[^"]*";'           = 'const char* MQTT_PASS = nullptr;'
  'const char\* DEVICE_ID = "[^"]*";'           = "const char* DEVICE_ID = `"tank-sim-$sim`";"
  '#define TOPIC "[^"]*"'                       = "#define TOPIC `"home/tanksim-$sim/tank/`""
  'MAX_RUN_MS     = 45UL \* 60 \* 1000;'        = 'MAX_RUN_MS     = 3UL * 60 * 1000; '
  'RISE_WINDOW_MS = 5UL \* 60 \* 1000;'         = 'RISE_WINDOW_MS = 20UL * 1000;     '
  'MIN_OFF_MS     = 60UL \* 1000;'              = 'MIN_OFF_MS     = 10UL * 1000;'
}
foreach ($e in $edits.GetEnumerator()) {
  if ($code -notmatch $e.Key) { throw "make_sim: pattern not found in the firmware: $($e.Key)" }
  $code = [regex]::Replace($code, $e.Key, $e.Value.Replace('$', '$$'))
}
$head = "// WOKWI SIMULATION COPY, generated by simulation\make_sim.ps1 from firmware\water_tank_controller.`r`n" +
        "// Edit the real firmware and re-run the script. Timers are shortened: max run 3 min, dry-run window 20 s, rest 10 s.`r`n"
[IO.File]::WriteAllText($dst, $head + $code, (New-Object Text.UTF8Encoding $false))
Write-Host "Wrote $dst (topics: home/tanksim-$sim/tank/...)"
